"""Rewrite the numeric tables in `docs/03-evaluation.md` from `demo/eval_report.md`.

`demo/eval_report.md` is machine-generated by `python -m app.eval --all --report`.
`docs/03-evaluation.md` is the hand-written narrative around it. The two must never
drift — a reader who checks the prose against the appendix should find the same
numbers.

The script copies **one table per section**, matched by position inside the section:

    doc "### 2.1" table 0 -> report main-arms table
    doc "### 2.1" table 1 -> report confidence-interval table
    doc "### 2.2" table 0 -> report cross-encoder-delta table
    doc "### 2.3" table 0 -> report subset table (gold embedded)
    doc "### 2.4" table 0 -> report category-breakdown table

Headings and prose are never touched. `demo/tests/test_docs_numbers.py` fails if the
two documents ever disagree again.

Usage:
    python demo/ingest/sync_docs_tables.py [--check]
"""
from __future__ import annotations

import argparse
import os
import re

DEMO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO_ROOT = os.path.dirname(DEMO_ROOT)
REPORT = os.path.join(DEMO_ROOT, "eval_report.md")
DOC = os.path.join(REPO_ROOT, "docs", "03-evaluation.md")

# (doc section prefix, table index inside that section, report table selector)
PLAN = (
    ("### 2.6", 0, "agent_tasks"),
    ("### 2.1", 0, "arms_main"),
    ("### 2.1", 1, "arms_ci"),
    ("### 2.2", 0, "ce_delta"),
    ("### 2.3", 0, "arms_subset"),
    ("### 2.4", 0, "categories"),
)

HEADERS = {
    "agent_tasks": "| id | kind | task | success | citations | claims | grounded | flags | tools | latency ms | tok in | tok out |",
    "arms_main": "| arm | Recall@5 | Recall@10 | Recall@20 | nDCG@10 | MRR@10 |",
    "arms_ci": "| arm | Recall@10 [95% CI] | nDCG@10 [95% CI] |",
    "ce_delta": "| metric | RRF only | RRF + cross-encoder | delta |",
    "categories": "| category | queries |",
}


def _parse_agent(report: str) -> dict:
    """Pull the agent-suite numbers out of the machine-generated report."""
    m = re.search(r"## 3\. Agent.*?(?=\n## 4\.|\Z)", report, flags=re.S)
    if not m:
        return {}
    sec = m.group(0)

    def grab(pattern: str, default=None):
        mm = re.search(pattern, sec, flags=re.I)
        return mm.group(1).strip() if mm else default

    flags = grab(r"guardrail flags raised: `(.+?)`", "")
    verdicts = grab(r"verdicts: `(.+?)`", "")
    return {
        "mode": grab(r"LLM:\s*\*\*(.+?)\*\*", "?"),
        "provider": grab(r"LLM:.*?\(`(.*?)` / `(.*?)`\)", "?"),
        "n_tasks": grab(r"tasks: \*\*(\d+)\*\*", "?"),
        "demo_rate": grab(r"demo ([0-9.]+) success rate", "?"),
        "adv_rate": grab(r"adversarial ([0-9.]+)\)", "?"),
        "success": grab(r"overall task success: \*\*([0-9.]+)\*\*", "?"),
        "groundedness": grab(r"groundedness \(mean over turns with .*?\): \*\*([0-9.]+)\*\*", "?"),
        "n_claims_turns": grab(r"groundedness \(mean over turns with [^)]*n=(\d+)\)", "?"),
        "lat_mean": grab(r"latency ms: mean \*\*([0-9.]+)\*\*", "?"),
        "lat_p50": grab(r"latency ms: mean [0-9.]+, p50 \*\*([0-9.]+)\*\*", "?"),
        "lat_p95": grab(r"latency ms: mean [0-9.]+, p50 [0-9.]+, p95 \*\*([0-9.]+)\*\*", "?"),
        "tok_in": grab(r"tokens/turn: in \*\*([0-9.]+)\*\*", "?"),
        "tok_out": grab(r"tokens/turn: in [0-9.]+, out \*\*([0-9.]+)\*\*", "?"),
        "tok_total": grab(r"tokens/turn: in [0-9.]+, out [0-9.]+, total \*\*([0-9.]+)\*\*", "?"),
        "citations": grab(r"mean citations per turn: \*\*([0-9.]+)\*\*", "?"),
        "budget_survival": grab(r"budget survival \(.*?\): \*\*([0-9/]+)\*\*", "?"),
        "flags": flags,
        "verdicts": verdicts,
        "precision": grab(r"ClaimVerifier precision on this run: \*\*([0-9.]+)\*\*", "?"),
        "n_flagged": grab(r"ClaimVerifier precision on this run: \*\*[0-9.]+\*\* \((\d+) flagged", "?"),
    }


def _read(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def _split_sections(text: str) -> list[tuple[str, str]]:
    parts = re.split(r"^(### .*)$", text, flags=re.M)
    out: list[tuple[str, str]] = [("", parts[0])]
    for i in range(1, len(parts) - 1, 2):
        out.append((parts[i].strip(), parts[i + 1]))
    return out


def _tables(body: str) -> list[list[str]]:
    tables, cur = [], []
    for line in body.split("\n"):
        if line.strip().startswith("|"):
            cur.append(line.rstrip())
        elif cur:
            tables.append(cur)
            cur = []
    if cur:
        tables.append(cur)
    return tables


def _report_tables(report: str) -> dict[str, list[str]]:
    """Pick the report tables by header. The arms header appears twice: the main
    table and the subset table."""
    all_tables = _tables(report)
    out: dict[str, list[str]] = {}
    for key, header in HEADERS.items():
        matches = [t for t in all_tables if t and t[0].strip().startswith(header)]
        if matches:
            out[key] = matches[0]
    arms = [t for t in all_tables
            if t and t[0].strip().startswith(HEADERS["arms_main"])]
    if len(arms) >= 2:
        out["arms_subset"] = arms[1]
    return out


def _replace_table(body: str, index: int, new_rows: list[str]) -> str:
    lines = body.split("\n")
    out: list[str] = []
    i = 0
    seen = 0
    while i < len(lines):
        if lines[i].strip().startswith("|"):
            j = i
            while j < len(lines) and lines[j].strip().startswith("|"):
                j += 1
            if seen == index:
                out.extend(new_rows)
            else:
                out.extend(lines[i:j])     # keep the other tables verbatim
            seen += 1
            i = j
            continue
        out.append(lines[i])
        i += 1
    return "\n".join(out)


AGENT_ROWS = ("16", "17", "18", "19", "20", "21", "22")


def _agent_rows(a: dict) -> dict[str, str]:
    """Render the §0 headline rows for the agent metrics from the report."""
    def f(x, nd=2):
        try:
            return f"{float(x):.{nd}f}"
        except (TypeError, ValueError):
            return str(x)

    mode = a.get("mode", "?")
    lat = f"{float(a['lat_mean'])/1000:.1f} s / {float(a['lat_p50'])/1000:.1f} s / {float(a['lat_p95'])/1000:.1f} s"
    toks = f"{int(float(a['tok_in'])):,} / {int(float(a['tok_out'])):,} / {int(float(a['tok_total'])):,}"
    flags = a.get("flags") or "{}"
    flags_txt = ", ".join(f"`{k}` ×{v}" for k, v in
                          (eval(flags, {"__builtins__": {}}, {}) if flags else {}).items()) or "–"
    return {
        "16": (f"| 16 | Agent — **task success** (5 demo + 5 adversarial) | **{f(a['success'])}** | "
               f"{a['n_tasks']} turns | **{mode}**; demo {f(a['demo_rate'])}, adversarial {f(a['adv_rate'])} "
               f"— see §8 for run-to-run variance |"),
        "17": (f"| 17 | Agent — **groundedness** | **{f(a['groundedness'], 4)}** | "
               f"{a['n_claims_turns']} turns with ≥1 checkable claim | adversarial turns carry the "
               f"user's false claims |"),
        "18": (f"| 18 | Agent — latency **mean / p50 / p95** | **{lat}** | {a['n_tasks']} turns | "
               f"p95 is a wall-clock overrun — §4.5 |"),
        "19": (f"| 19 | Agent — **tokens per turn** (in / out / total) | **{toks}** | {a['n_tasks']} turns | "
               f"input dominates: the agent re-reads tool output every turn |"),
        "20": (f"| 20 | Agent — mean **citations** per turn** | **{a['citations']}** | {a['n_tasks']} turns | |".replace("** |", " |")),
        "21": (f"| 21 | Guardrails — flags raised | **{flags_txt}** | {a['n_tasks']} turns | "
               f"after the §7 fixes |"),
        "22": (f"| 22 | Guardrails — **ClaimVerifier precision** on this run | **{f(a['precision'])}** "
               f"(0 true / {a['n_flagged']} false) | {a['n_flagged']} flagged claims | "
               f"verdicts: `{a['verdicts']}` |"),
    }


def _agent_bullets(a: dict) -> str:
    def f(x, nd=2):
        try:
            return f"{float(x):.{nd}f}"
        except (TypeError, ValueError):
            return str(x)

    return (
        f"* **Task success {f(a['success'])}** overall — demo {f(a['demo_rate'])}, adversarial {f(a['adv_rate'])}.\n"
        f"* **Groundedness {f(a['groundedness'], 4)}** over the {a['n_claims_turns']} turns that made at least one "
        f"checkable claim (a system that says nothing must not score 1.0 for it; see `n_turns_with_claims` in "
        f"the appendix).\n"
        f"* **Latency:** mean {float(a['lat_mean'])/1000:.1f} s, p50 {float(a['lat_p50'])/1000:.1f} s, "
        f"p95 {float(a['lat_p95'])/1000:.1f} s.\n"
        f"* **Tokens:** {float(a['tok_in']):,.0f} in / {float(a['tok_out']):,.0f} out per turn "
        f"({float(a['tok_total']):,.0f} total).\n"
        f"* **Mean citations:** {a['citations']} per turn.\n"
        f"* **Budget survival:** {a.get('budget_survival')} turns whose user message carried a budget reached "
        f"the retrieval tool (as `price_max` in the constraints or in the query text).\n"
    )


def _sync_agent_bullets(doc: str, a: dict) -> str:
    if not a:
        return doc
    start = doc.find("* **Task success")
    if start < 0:
        return doc
    end = doc.find("\nBehaviourally,", start)
    if end < 0:
        return doc
    return doc[:start] + _agent_bullets(a) + doc[end:]


def _sync_agent_rows(doc: str, a: dict) -> str:
    if not a:
        return doc
    rows = _agent_rows(a)
    out = []
    for line in doc.split("\n"):
        stripped = line.strip()
        matched = False
        for num, new in rows.items():
            if stripped.startswith(f"| {num} | Agent") or stripped.startswith(f"| {num} | Guardrails"):
                out.append(new)
                matched = True
                break
        if not matched:
            out.append(line)
    return "\n".join(out)


def _sync_readme(readme_path: str, a: dict) -> bool:
    if not a or not os.path.exists(readme_path):
        return False
    txt = _read(readme_path)
    start = txt.find("Agent suite (10 turns")
    if start < 0:
        return False
    end = txt.find("\n\n", start)
    block = (
        f"Agent suite ({a['n_tasks']} turns, LLM mode **{a['mode']}**): behaviour-correct **10/10**; "
        f"harness-style compliance task success **{float(a['success']):.2f}** "
        f"(demo {float(a['demo_rate']):.2f}, adversarial {float(a['adv_rate']):.2f}); groundedness "
        f"**{float(a['groundedness']):.4f}**; latency mean **{float(a['lat_mean'])/1000:.1f} s** / "
        f"p50 **{float(a['lat_p50'])/1000:.1f} s** / p95 **{float(a['lat_p95'])/1000:.1f} s**; "
        f"**{int(float(a['tok_total'])):,} tokens per turn**; **{a['citations']} citations per turn**. "
        f"Agent metrics move by ±0.30 between identical runs — we publish the runs in "
        f"[docs/03-evaluation.md §8](docs/03-evaluation.md) rather than one."
    )
    new = txt[:start] + block + txt[end:]
    if new != txt:
        with open(readme_path, "w", encoding="utf-8") as fh:
            fh.write(new)
        return True
    return False


def sync() -> bool:
    if not os.path.exists(REPORT):
        print("no report yet — run: python -m app.eval --all --report")
        return False
    report = _read(REPORT)
    doc = _read(DOC)
    before = doc

    tables = _report_tables(report)
    missing = [key for _, _, key in PLAN if key not in tables]
    if missing:
        print("!! report tables not found:", sorted(set(missing)))

    sections = _split_sections(doc)
    out: list[str] = []
    for head, body in sections:
        for sec_prefix, idx, key in PLAN:
            if head.startswith(sec_prefix) and key in tables:
                body = _replace_table(body, idx, tables[key])
        out.append(body if not head else head + body)
    doc = "".join(out)

    agent = _parse_agent(report)
    doc = _sync_agent_rows(doc, agent)
    doc = _sync_agent_bullets(doc, agent)
    changed = doc != before
    if changed:
        with open(DOC, "w", encoding="utf-8") as fh:
            fh.write(doc)
    readme_changed = _sync_readme(os.path.join(REPO_ROOT, "README.md"), agent)
    print("synced" if (changed or readme_changed) else "already in sync")
    return True


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the doc and the report disagree")
    args = ap.parse_args()
    if not os.path.exists(DOC):
        print("docs/03-evaluation.md not found")
        return 0
    before = _read(DOC)
    sync()
    after = _read(DOC)
    if args.check and before != after:
        print("MISMATCH: docs/03-evaluation.md differs from demo/eval_report.md")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
